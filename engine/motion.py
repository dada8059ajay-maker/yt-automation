#!/usr/bin/env python3
"""Zero-face-morph 2.5D motion (CPU, free). The character pixels are CUT OUT of the Hark picture (rembg) and MOVED as a
layer over an inpainted background: parallax, walk-bob, push-in, handheld shake, hook punch-in. Nothing is regenerated by
AI, so faces/characters stay 100% identical in every frame. usage: animate(img, out_mp4, seconds, ch, scene_idx)"""
import os, sys, math, subprocess
import numpy as np, cv2

W, H, FPS = 1920, 1080, 30
_SESSION = None

def _mask(img_bgr):
    global _SESSION
    from rembg import remove, new_session
    if _SESSION is None: _SESSION = new_session("u2net")
    rgba = remove(cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB), session=_SESSION)
    return np.asarray(rgba)[:, :, 3].astype(np.float32) / 255.0

def _layers(img):
    try: a = _mask(img)
    except Exception as e:
        print("motion: rembg unavailable, camera-only", repr(e)[:80], flush=True); return img, None
    cover = float((a > 0.5).mean())
    if cover < 0.02 or cover > 0.70: return img, None          # no clean subject -> camera-only moves
    hard = (a > 0.3).astype(np.uint8) * 255
    dil = cv2.dilate(hard, np.ones((25, 25), np.uint8))
    s = 0.5; small = cv2.resize(img, None, fx=s, fy=s); sm = cv2.resize(dil, None, fx=s, fy=s)
    fill = cv2.resize(cv2.inpaint(small, sm, 6, cv2.INPAINT_TELEA), (img.shape[1], img.shape[0]))
    m3 = (dil > 0)[:, :, None]; bg = np.where(m3, cv2.GaussianBlur(fill, (0, 0), 3), img)
    alpha = cv2.GaussianBlur(a, (0, 0), 1.5)[:, :, None]
    return bg, alpha

def _aff(scale, dx, dy, rot=0.0):
    M = cv2.getRotationMatrix2D((W / 2, H / 2), rot, scale); M[0, 2] += dx; M[1, 2] += dy; return M

def animate(image, out_mp4, seconds, ch="kahani", idx=0, fx=None, fps=None, crf="18", preset="medium"):
    """fx: list of living-picture effects (engine/fx.py) applied to the background every frame (water flows, fire, wind...)."""
    FPS = int(fps or globals()["FPS"])
    img = cv2.resize(cv2.imread(image), (W, H), interpolation=cv2.INTER_AREA)
    bg, alpha = _layers(img)
    live = None
    if fx:
        from fx import FX
        live = FX(img if alpha is None else bg, fx, idx)
        if not live.active: live = None
    fg = img.astype(np.float32)
    n = max(2, int(math.ceil(seconds * FPS)))
    sgn = 1 if idx % 2 == 0 else -1                            # alternate direction scene to scene
    rng = np.random.default_rng(idx + 7)
    shake_amp = 5.0 if ch == "raat" else 1.5
    ph = rng.uniform(0, 6.28, 4)
    p = subprocess.Popen(["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-",
                          "-c:v", "libx264", "-preset", preset, "-crf", crf, "-pix_fmt", "yuv420p", out_mp4], stdin=subprocess.PIPE)
    for f in range(n):
        t = f / (n - 1); e = t * t * (3 - 2 * t); sec = f / FPS
        cam = 1.06 + 0.07 * e                                  # slow push-in on the whole scene
        if idx == 0: cam += 0.22 * math.exp(-sec / 0.28)        # HOOK: hard punch-in that settles in ~0.6 s
        sx = shake_amp * (math.sin(sec * 7.1 + ph[0]) + 0.5 * math.sin(sec * 13.3 + ph[1]))
        sy = shake_amp * (math.sin(sec * 6.3 + ph[2]) + 0.5 * math.sin(sec * 11.7 + ph[3]))
        if idx == 0 and sec < 0.5: sx += 18 * math.sin(sec * 60) * (1 - sec / 0.5)   # impact jolt
        cdx = sgn * 40 * (e - 0.5) + sx
        src = live.frame(sec) if live is not None else None
        if alpha is None:
            frame = cv2.warpAffine(img if src is None else src, _aff(cam, cdx, sy), (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT)
        else:
            b = cv2.warpAffine(bg if src is None else src, _aff(cam, cdx * 0.6, sy * 0.6), (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT)
            bob = 7 * abs(math.sin(sec * math.pi * 1.8))           # walk / breathing bob
            fdx = cdx + sgn * 70 * (e - 0.5)                       # character travels across the frame (parallax)
            M = _aff(cam * (1.0 + 0.03 * e), fdx, sy - bob, rot=0.6 * math.sin(sec * 2.2))
            fgw = cv2.warpAffine(fg, M, (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT)
            aw = cv2.warpAffine(alpha, M, (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT)[:, :, None]
            frame = (b.astype(np.float32) * (1 - aw) + fgw * aw)
        if ch == "raat": frame = frame * (0.93 + 0.07 * (0.5 + 0.5 * math.sin(sec * 9 + ph[0])))   # lantern flicker
        if idx == 0 and sec < 0.12: k = 0.7 * (1 - sec / 0.12); frame = frame * (1 - k) + 255 * k   # white flash on frame 1
        p.stdin.write(np.clip(frame, 0, 255).astype(np.uint8).tobytes())
    p.stdin.close(); p.wait()
    if p.returncode: raise RuntimeError("ffmpeg motion encode failed")
    return out_mp4, alpha is not None

if __name__ == "__main__":
    o, lay = animate(sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4] if len(sys.argv) > 4 else "kahani", int(sys.argv[5]) if len(sys.argv) > 5 else 0)
    print("motion OK", o, "layered" if lay else "camera-only")
